#!/usr/bin/env python3
"""Build web/dict.js from the English–Bangla dictionary dataset.

Source: https://github.com/Nafisa41/Dictionary--English-to-Bangla-
Original data: https://github.com/MinhasKamal/BengaliDictionary

The dataset is downloaded once, cleaned, sorted and written as a compact
JavaScript array so the app can look words up entirely offline.

Usage:
    python scripts/build-dict.py [path-to-E2Bdatabase.json]
"""
from __future__ import annotations

import json
import sys
import tempfile
import urllib.request
from pathlib import Path

SOURCE_URL = (
    "https://raw.githubusercontent.com/Nafisa41/"
    "Dictionary--English-to-Bangla-/master/Database/E2Bdatabase.json"
)
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "web" / "dict.js"


def load_source(path: Path | None) -> list[dict]:
    if path is not None:
        return json.loads(path.read_text(encoding="utf-8"))
    cache = Path(tempfile.gettempdir()) / "kotha-koi-e2b.json"
    if not cache.exists():
        print(f"Downloading {SOURCE_URL}")
        with urllib.request.urlopen(SOURCE_URL, timeout=120) as response:
            cache.write_bytes(response.read())
    return json.loads(cache.read_text(encoding="utf-8"))


def main() -> None:
    source = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else None
    rows = load_source(source)

    seen: set[str] = set()
    entries: list[tuple[str, str]] = []
    for row in rows:
        en = str(row.get("en", "")).strip()
        bn = str(row.get("bn", "")).strip()
        if not en or not bn:
            continue
        key = en.casefold()
        if key in seen:
            continue
        seen.add(key)
        entries.append((en, bn))

    entries.sort(key=lambda item: (item[0].casefold(), item[0]))

    payload = json.dumps(entries, ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text(
        "/* English–Bangla dictionary. Generated by scripts/build-dict.py.\n"
        "   Source: github.com/Nafisa41/Dictionary--English-to-Bangla-\n"
        "   Original: github.com/MinhasKamal/BengaliDictionary */\n"
        "window.KK_DICT=" + payload + ";\n",
        encoding="utf-8",
    )
    size = OUTPUT.stat().st_size
    print(f"Wrote {OUTPUT} — {len(entries):,} words, {size / 1_000_000:.1f} MB")


if __name__ == "__main__":
    main()
